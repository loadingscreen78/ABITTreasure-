// Concatenates supabase/migrations/*.sql into supabase/combined.sql for pasting into
// Supabase → SQL Editor (alternative to `npm run db:push`). Safe to run more than once.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const out = files.map((f) => `-- ===== ${f} =====\n${readFileSync(`${dir}/${f}`, "utf8")}`).join("\n\n");
writeFileSync("supabase/combined.sql", `-- Generated by scripts/build-sql.mjs — paste into Supabase SQL Editor and Run.\n\n${out}`);
console.log(`wrote supabase/combined.sql (${files.length} migrations)`);
